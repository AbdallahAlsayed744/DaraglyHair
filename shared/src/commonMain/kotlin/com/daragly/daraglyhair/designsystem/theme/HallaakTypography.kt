package com.daragly.daraglyhair.designsystem.theme

import androidx.compose.runtime.Composable
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp
import daraglyhair.shared.generated.resources.Res
import daraglyhair.shared.generated.resources.cairo_bold
import daraglyhair.shared.generated.resources.cairo_regular
import org.jetbrains.compose.resources.Font

// ─────────────────────────────────────────────
//  Halla'ak Typography
//
//  Font: Cairo – Arabic-first font family,
//  same as Delivery-User.
//
//  In CMP fonts are loaded from
//  composeResources/font/ via Res.font.*
//  (generated by the Compose Resources plugin).
//
//  Cairo is declared as a @Composable val because
//  Font(resource = ...) is a composable call in
//  Compose Multiplatform.
// ─────────────────────────────────────────────

val localHallaakTypography =
    staticCompositionLocalOf<HallaakTypography> { error("HallaakTypography not provided") }

// ── Cairo font family (composable) ───────────

@Composable
fun cairoFontFamily(): FontFamily = FontFamily(
    Font(resource = Res.font.cairo_regular, weight = FontWeight.Normal),
    Font(resource = Res.font.cairo_bold,    weight = FontWeight.Bold),
)

// ── Data models ───────────────────────────────

data class HallaakTypography(
    val headline: HallaakSizedTypography,
    val title: HallaakSizedTypography,
    val body: HallaakSizedTypography,
    val label: HallaakSizedTypography,
)

data class HallaakSizedTypography(
    val extraLarge: TextStyle,
    val large: TextStyle,
    val medium: TextStyle,
    val small: TextStyle,
    val extraSmall: TextStyle,
)

// ── Scale builders ────────────────────────────

private fun headlineScale(cairo: FontFamily) = HallaakSizedTypography(
    extraLarge = TextStyle(fontFamily = cairo, fontSize = 32.sp, lineHeight = 40.sp, fontWeight = FontWeight.Bold),
    large      = TextStyle(fontFamily = cairo, fontSize = 24.sp, lineHeight = 32.sp, fontWeight = FontWeight.Bold),
    medium     = TextStyle(fontFamily = cairo, fontSize = 20.sp, lineHeight = 28.sp, fontWeight = FontWeight.Bold),
    small      = TextStyle(fontFamily = cairo, fontSize = 18.sp, lineHeight = 26.sp, fontWeight = FontWeight.Bold),
    extraSmall = TextStyle(fontFamily = cairo, fontSize = 16.sp, lineHeight = 24.sp, fontWeight = FontWeight.Bold),
)

private fun titleScale(cairo: FontFamily) = HallaakSizedTypography(
    extraLarge = TextStyle(fontFamily = cairo, fontSize = 16.sp, lineHeight = 24.sp, fontWeight = FontWeight.Bold),
    large      = TextStyle(fontFamily = cairo, fontSize = 14.sp, lineHeight = 22.sp, fontWeight = FontWeight.Bold),
    medium     = TextStyle(fontFamily = cairo, fontSize = 13.sp, lineHeight = 20.sp, fontWeight = FontWeight.Bold),
    small      = TextStyle(fontFamily = cairo, fontSize = 12.sp, lineHeight = 18.sp, fontWeight = FontWeight.Bold),
    extraSmall = TextStyle(fontFamily = cairo, fontSize = 11.sp, lineHeight = 16.sp, fontWeight = FontWeight.Bold),
)

private fun bodyScale(cairo: FontFamily) = HallaakSizedTypography(
    extraLarge = TextStyle(fontFamily = cairo, fontSize = 18.sp, lineHeight = 28.sp, fontWeight = FontWeight.Normal),
    large      = TextStyle(fontFamily = cairo, fontSize = 16.sp, lineHeight = 26.sp, fontWeight = FontWeight.Normal),
    medium     = TextStyle(fontFamily = cairo, fontSize = 15.sp, lineHeight = 24.sp, fontWeight = FontWeight.Normal),
    small      = TextStyle(fontFamily = cairo, fontSize = 14.sp, lineHeight = 22.sp, fontWeight = FontWeight.Normal),
    extraSmall = TextStyle(fontFamily = cairo, fontSize = 13.sp, lineHeight = 20.sp, fontWeight = FontWeight.Normal),
)

private fun labelScale(cairo: FontFamily) = HallaakSizedTypography(
    extraLarge = TextStyle(fontFamily = cairo, fontSize = 13.sp, lineHeight = 18.sp, fontWeight = FontWeight.Normal),
    large      = TextStyle(fontFamily = cairo, fontSize = 12.sp, lineHeight = 16.sp, fontWeight = FontWeight.Normal),
    medium     = TextStyle(fontFamily = cairo, fontSize = 11.sp, lineHeight = 16.sp, fontWeight = FontWeight.Normal),
    small      = TextStyle(fontFamily = cairo, fontSize = 10.sp, lineHeight = 14.sp, fontWeight = FontWeight.Normal),
    extraSmall = TextStyle(fontFamily = cairo, fontSize = 9.sp,  lineHeight = 12.sp, fontWeight = FontWeight.Normal),
)

// ── Factory (called once in HallaakTheme) ─────

@Composable
fun buildHallaakTypography(): HallaakTypography {
    val cairo = cairoFontFamily()
    return HallaakTypography(
        headline = headlineScale(cairo),
        title    = titleScale(cairo),
        body     = bodyScale(cairo),
        label    = labelScale(cairo),
    )
}
